export function XAU(type) {
    return type.charAt(0).toUpperCase() + 'AU';
}

export function XAPU(type) {
    return type.charAt(0).toUpperCase() + 'APU';
}

export function XAAPU(type) {
    return type.charAt(0).toUpperCase() + 'AAPU';
}

export function ARPXAU(type) {
    return 'ARP' + type.charAt(0).toUpperCase() + 'AU';
}

